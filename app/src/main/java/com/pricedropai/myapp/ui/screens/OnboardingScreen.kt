package com.pricedropai.myapp.ui.screens

import androidx.compose.animation.*
import androidx.compose.animation.core.tween
import androidx.compose.foundation.background
import androidx.compose.foundation.gestures.detectHorizontalDragGestures
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.automirrored.filled.TrendingDown
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.input.pointer.pointerInput
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextAlign
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.pricedropai.myapp.ui.theme.*
import kotlinx.coroutines.delay

data class OnboardingStep(
    val title: String,
    val subtitle: String,
    val icon: ImageVector,
    val accentColors: List<Color>,
    val badgeText: String,
    val keyHighlight: String
)

@Composable
fun OnboardingScreen(
    onFinishOnboarding: () -> Unit
) {
    val steps = remember {
        listOf(
            OnboardingStep(
                title = "Multi-Store Price Tracking",
                subtitle = "Track real-time pricing across Amazon, Meesho, Flipkart, and Myntra all in one place.",
                icon = Icons.Default.Storefront,
                accentColors = listOf(Color(0xFF6366F1), Color(0xFF4F46E5)),
                badgeText = "Step 1 of 8 • Multi-Store",
                keyHighlight = "Compare live prices across 4 verified retailers simultaneously."
            ),
            OnboardingStep(
                title = "Instant Price-Drop Alerts",
                subtitle = "Set custom price target thresholds. Receive instant high-priority notifications the exact moment a product price drops.",
                icon = Icons.Default.NotificationsActive,
                accentColors = listOf(Color(0xFFEC4899), Color(0xFFBE185D)),
                badgeText = "Step 2 of 8 • Instant Alerts",
                keyHighlight = "Never miss flash sales or sudden midnight price drops again."
            ),
            OnboardingStep(
                title = "Historical Price Charts",
                subtitle = "Explore interactive price history graphs. Know all-time lows, highs, price trends, and whether today is truly the best time to buy.",
                icon = Icons.AutoMirrored.Filled.TrendingDown,
                accentColors = listOf(Color(0xFF10B981), Color(0xFF047857)),
                badgeText = "Step 3 of 8 • Price History",
                keyHighlight = "Transparent analytics so you never fall for inflated discounts."
            ),
            OnboardingStep(
                title = "Bank Offers & Card Discounts",
                subtitle = "Calculate the real out-of-pocket price with automated bank offer calculation for HDFC, ICICI, SBI, Axis, and cashback cards.",
                icon = Icons.Default.CreditCard,
                accentColors = listOf(Color(0xFFF59E0B), Color(0xFFD97706)),
                badgeText = "Step 4 of 8 • Smart Savings",
                keyHighlight = "Instant EMI and instant discount breakdown at your fingertips."
            ),
            OnboardingStep(
                title = "AI Review Summarizer",
                subtitle = "Let AI synthesize thousands of verified customer reviews into key pros, cons, and a reliable confidence score in seconds.",
                icon = Icons.Default.RateReview,
                accentColors = listOf(Color(0xFF8B5CF6), Color(0xFF6D28D9)),
                badgeText = "Step 5 of 8 • Review Insights",
                keyHighlight = "Zero fluff — direct product insights generated by AI."
            ),
            OnboardingStep(
                title = "AI Copilot Shopping Assistant",
                subtitle = "Chat directly with our shopping copilot. Ask for product comparisons, alternative recommendations, and personalized deal suggestions.",
                icon = Icons.Default.SmartToy,
                accentColors = listOf(Color(0xFF06B6D4), Color(0xFF0E7490)),
                badgeText = "Step 6 of 8 • AI Copilot",
                keyHighlight = "Powered by modern neural models for smart shopping advice."
            ),
            OnboardingStep(
                title = "Smart Wishlist & Background Engine",
                subtitle = "Save your dream gadgets and fashion items. Our lightweight background engine monitors price fluctuations with zero battery drain.",
                icon = Icons.Default.Favorite,
                accentColors = listOf(Color(0xFFEF4444), Color(0xFFB91C1C)),
                badgeText = "Step 7 of 8 • Set & Forget",
                keyHighlight = "Sync your tracked items locally and securely on your device."
            ),
            OnboardingStep(
                title = "Free Service Search Limit",
                subtitle = "PriceDrop AI is 100% free with live scrapers! Due to free tier cloud services, at a time search only 2 to 3 products to prevent server throttling and maintain blazing fast comparison speed.",
                icon = Icons.Default.Tune,
                accentColors = listOf(Color(0xFF0284C7), Color(0xFF0369A1)),
                badgeText = "Step 8 of 8 • Free Fair Usage",
                keyHighlight = "Due to free services, at a time search only 2–3 products."
            )
        )
    }

    var currentStepIndex by remember { mutableIntStateOf(0) }
    // Timer reset key: increments whenever user manually swipes or auto-advances
    var userInteractionTrigger by remember { mutableLongStateOf(0L) }
    var slideDirectionForward by remember { mutableStateOf(true) }

    val currentStep = steps[currentStepIndex]

    // 5-second automatic progression per page (overridden/reset when user performs swipe)
    LaunchedEffect(currentStepIndex, userInteractionTrigger) {
        delay(5000)
        if (currentStepIndex < steps.size - 1) {
            slideDirectionForward = true
            currentStepIndex += 1
        } else {
            onFinishOnboarding()
        }
    }

    var totalDragX by remember { mutableFloatStateOf(0f) }

    Surface(
        modifier = Modifier
            .fillMaxSize()
            .pointerInput(Unit) {
                detectHorizontalDragGestures(
                    onDragStart = { totalDragX = 0f },
                    onHorizontalDrag = { _, dragAmount ->
                        totalDragX += dragAmount
                    },
                    onDragEnd = {
                        val swipeThreshold = 50f
                        if (totalDragX < -swipeThreshold) {
                            // Swipe Left -> Go forward (Next)
                            if (currentStepIndex < steps.size - 1) {
                                slideDirectionForward = true
                                currentStepIndex += 1
                                userInteractionTrigger = System.currentTimeMillis()
                            } else {
                                onFinishOnboarding()
                            }
                        } else if (totalDragX > swipeThreshold) {
                            // Swipe Right -> Go backward (Previous)
                            if (currentStepIndex > 0) {
                                slideDirectionForward = false
                                currentStepIndex -= 1
                                userInteractionTrigger = System.currentTimeMillis()
                            }
                        }
                    }
                )
            },
        color = MaterialTheme.colorScheme.background
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(24.dp),
            verticalArrangement = Arrangement.SpaceBetween
        ) {
            // Top Bar: Step Pill only (No skip button as per requirement)
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(top = 16.dp),
                horizontalArrangement = Arrangement.Center,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Surface(
                    shape = RoundedCornerShape(20.dp),
                    color = MaterialTheme.colorScheme.surfaceVariant,
                    modifier = Modifier.padding(vertical = 4.dp)
                ) {
                    Text(
                        text = currentStep.badgeText,
                        modifier = Modifier.padding(horizontal = 16.dp, vertical = 6.dp),
                        fontSize = 12.sp,
                        fontWeight = FontWeight.SemiBold,
                        color = MaterialTheme.colorScheme.primary
                    )
                }
            }

            // Animated Center Content with swipe transition effects
            AnimatedContent(
                targetState = currentStepIndex,
                transitionSpec = {
                    if (slideDirectionForward) {
                        (slideInHorizontally(animationSpec = tween(400)) { width -> width } + fadeIn(animationSpec = tween(400)))
                            .togetherWith(slideOutHorizontally(animationSpec = tween(400)) { width -> -width } + fadeOut(animationSpec = tween(400)))
                    } else {
                        (slideInHorizontally(animationSpec = tween(400)) { width -> -width } + fadeIn(animationSpec = tween(400)))
                            .togetherWith(slideOutHorizontally(animationSpec = tween(400)) { width -> width } + fadeOut(animationSpec = tween(400)))
                    }
                },
                label = "onboarding_step_anim",
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1f)
            ) { stepIdx ->
                val step = steps[stepIdx]
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(vertical = 24.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.Center
                ) {
                    // Feature Icon Box with vibrant glowBackdrop and neon border
                    Box(
                        modifier = Modifier
                            .size(112.dp)
                            .glowBackdrop(glowColor = step.accentColors.first(), minAlpha = 0.3f, maxAlpha = 0.8f)
                            .clip(RoundedCornerShape(32.dp))
                            .neonGlow(
                                color = step.accentColors.first(),
                                secondaryColor = step.accentColors.last(),
                                shape = RoundedCornerShape(32.dp),
                                borderWidth = 1.5.dp
                            )
                            .background(
                                Brush.linearGradient(colors = step.accentColors)
                            )
                            .shimmerSweep(shimmerColor = Color.White.copy(alpha = 0.15f), durationMillis = 2000),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = step.icon,
                            contentDescription = step.title,
                            tint = Color.White,
                            modifier = Modifier.size(56.dp)
                        )
                    }

                    Spacer(Modifier.height(32.dp))

                    Text(
                        text = step.title,
                        fontSize = 24.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onBackground,
                        textAlign = TextAlign.Center
                    )

                    Spacer(Modifier.height(14.dp))

                    Text(
                        text = step.subtitle,
                        fontSize = 14.sp,
                        lineHeight = 21.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        textAlign = TextAlign.Center,
                        modifier = Modifier.padding(horizontal = 12.dp)
                    )

                    Spacer(Modifier.height(24.dp))

                    Surface(
                        shape = RoundedCornerShape(16.dp),
                        color = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.65f),
                        border = androidx.compose.foundation.BorderStroke(
                            1.dp,
                            step.accentColors.first().copy(alpha = 0.4f)
                        ),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Row(
                            modifier = Modifier.padding(14.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Icon(
                                imageVector = Icons.Default.CheckCircle,
                                contentDescription = null,
                                tint = step.accentColors.first(),
                                modifier = Modifier.size(20.dp)
                            )
                            Spacer(Modifier.width(10.dp))
                            Text(
                                text = step.keyHighlight,
                                fontSize = 12.sp,
                                fontWeight = FontWeight.Medium,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                        }
                    }
                }
            }

            // Bottom Navigation: Indicator Dots & Swipe prompt (No next/skip buttons)
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(bottom = 20.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                // Indicator dots for 7 pages
                Row(
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    modifier = Modifier.padding(bottom = 12.dp)
                ) {
                    for (i in steps.indices) {
                        Box(
                            modifier = Modifier
                                .height(6.dp)
                                .width(if (i == currentStepIndex) 26.dp else 7.dp)
                                .then(
                                    if (i == currentStepIndex) {
                                        Modifier.glowBackdrop(glowColor = currentStep.accentColors.first(), minAlpha = 0.3f, maxAlpha = 0.8f)
                                    } else Modifier
                                )
                                .clip(CircleShape)
                                .background(
                                    if (i == currentStepIndex)
                                        currentStep.accentColors.first()
                                    else
                                        MaterialTheme.colorScheme.surfaceVariant
                                )
                        )
                    }
                }

                Text(
                    text = "Swipe left / right or wait 5s to continue",
                    fontSize = 11.sp,
                    color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
                    textAlign = TextAlign.Center
                )
            }
        }
    }
}
